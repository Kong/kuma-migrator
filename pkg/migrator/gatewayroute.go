// gatewayAPIVersionAlpha2 is the Gateway API group/version the experimental
// channel serves TCPRoute under. Note Kuma itself has never reconciled Gateway
// API TCPRoute (no TCPRouteReconciler exists at v2.14.4 or on master), so a
// TCPRoute emitted here is only meaningful to a third-party gateway
// implementation — see TransformMeshGatewayRoute's warning.
const gatewayAPIVersionAlpha2 = "gateway.networking.k8s.io/v1alpha2"

// sectionNameFromTags attempts to derive a Gateway listener sectionName from
// MeshGateway listener tags. The conventional tag key is "port" with a value
// like "http-8080" matching the listener name generated by gatewayListenerName.
func sectionNameFromTags(tags map[string]string) string {
	if v, ok := tags["port"]; ok {
		return v
	}
	// If there's exactly one tag and its value looks like a listener name, use it.
	if len(tags) == 1 {
		for _, v := range tags {
			if strings.Contains(v, "-") {
				return v
			}
		}
	}
	return ""
}

// ---- Input structs for MeshGatewayRoute (legacy) ----------------------------

type meshGatewayRoute struct {
	APIVersion string          `json:"apiVersion"`
	Kind       string          `json:"kind"`
	Mesh       string          `json:"mesh,omitempty"` // Universal-style top-level mesh field
	Metadata   gwRouteMetadata `json:"metadata"`
	Spec       gwRouteSpec     `json:"spec"`
}

type gwRouteMetadata struct {
	Name      string            `json:"name"`
	Namespace string            `json:"namespace,omitempty"`
	Labels    map[string]string `json:"labels,omitempty"`
}

type gwRouteSpec struct {
	Selectors []gwSelector `json:"selectors"`
	Conf      gwRouteConf  `json:"conf"`
}

type gwSelector struct {
	Match map[string]string `json:"match"`
}

type gwRouteConf struct {
	HTTP *gwHTTPConf `json:"http,omitempty"`
	TCP  *gwTCPConf  `json:"tcp,omitempty"`
}

type gwHTTPConf struct {
	Hostnames []string     `json:"hostnames,omitempty"`
	Rules     []gwHTTPRule `json:"rules"`
}

type gwHTTPRule struct {
	Matches  []gwHTTPMatch `json:"matches"`
	Filters  []gwFilter    `json:"filters,omitempty"`
	Backends []gwBackend   `json:"backends,omitempty"`
}

type gwHTTPMatch struct {
	Path            *gwPathMatch    `json:"path,omitempty"`
	Method          string          `json:"method,omitempty"`
	Headers         []gwHeaderMatch `json:"headers,omitempty"`
	QueryParameters []gwQueryMatch  `json:"query_parameters,omitempty"`
}

type gwPathMatch struct {
	Match string `json:"match"` // EXACT | PREFIX | REGEX
	Value string `json:"value"`
}

type gwHeaderMatch struct {
	Match string `json:"match"` // EXACT | REGEX | PRESENT | ABSENT
	Name  string `json:"name"`
	Value string `json:"value,omitempty"`
}

type gwQueryMatch struct {
	Match string `json:"match"` // EXACT | REGEX
	Name  string `json:"name"`
	Value string `json:"value"`
}

type gwFilter struct {
	RequestHeader  *gwHeaderFilter `json:"request_header,omitempty"`
	ResponseHeader *gwHeaderFilter `json:"response_header,omitempty"`
	Redirect       *gwRedirect     `json:"redirect,omitempty"`
	Rewrite        *gwRewrite      `json:"rewrite,omitempty"`
	Mirror         *gwMirror       `json:"mirror,omitempty"`
}

type gwHeaderFilter struct {
	Set    []gwNameValue `json:"set,omitempty"`
	Add    []gwNameValue `json:"add,omitempty"`
	Remove []string      `json:"remove,omitempty"`
}

type gwNameValue struct {
	Name  string `json:"name"`
	Value string `json:"value"`
}

type gwRedirect struct {
	Scheme     string     `json:"scheme,omitempty"`
	Hostname   string     `json:"hostname,omitempty"`
	Port       uint32     `json:"port,omitempty"`
	StatusCode uint32     `json:"status_code,omitempty"`
	Path       *gwRewrite `json:"path,omitempty"`
}

type gwRewrite struct {
	ReplaceFull        string `json:"replace_full,omitempty"`
	ReplacePrefixMatch string `json:"replace_prefix_match,omitempty"`
	HostToBackend      bool   `json:"host_to_backend_hostname,omitempty"`
}

type gwMirror struct {
	Percentage float64    `json:"percentage,omitempty"`
	Backend    *gwBackend `json:"backend,omitempty"`
}

type gwBackend struct {
	Weight      uint32            `json:"weight,omitempty"`
	Destination map[string]string `json:"destination,omitempty"`
}

type gwTCPConf struct {
	Rules []gwTCPRule `json:"rules"`
}

type gwTCPRule struct {
	Backends []gwBackend `json:"backends"`
}

// ---- Main transformer -------------------------------------------------------

// TransformMeshGatewayRoute converts a legacy MeshGatewayRoute into one or
// more Gateway API HTTPRoute or TCPRoute resources.
func TransformMeshGatewayRoute(raw []byte) ([][]byte, []string, error) {
	return TransformMeshGatewayRouteWithOptions(raw, TransformOptions{})
}

// TransformMeshGatewayRouteWithOptions is TransformMeshGatewayRoute with the
// cross-document context needed to point parentRefs at the Gateway actually
// emitted for the selected MeshGateway (opts.Gateways, see GatewayRefIndex).
func TransformMeshGatewayRouteWithOptions(raw []byte, opts TransformOptions) ([][]byte, []string, error) {
	var route meshGatewayRoute
	if err := yaml.Unmarshal(raw, &route); err != nil {
		return nil, nil, fmt.Errorf("unmarshal MeshGatewayRoute: %w", err)
	}

	if route.Spec.Conf.HTTP != nil {
		docs, warnings, err := transformGWHTTPRoute(route, opts.Gateways)
		return docs, append(warnings, gatewayRouteSuccessorNote(route.Metadata.Name, false)), err
	}
	if route.Spec.Conf.TCP != nil {
		docs, warnings, err := transformGWTCPRoute(route, opts.Gateways)
		return docs, append(warnings, gatewayRouteSuccessorNote(route.Metadata.Name, true)), err
	}
	return nil, []string{fmt.Sprintf("MeshGatewayRoute %q: no conf.http or conf.tcp section found — skipped", route.Metadata.Name)}, nil
}

// gatewayRouteSuccessorNote states which of the two possible destinations this
// conversion picked, and which one upstream names.
//
// UPGRADE.md's "Built-in gateway no longer falls back to MeshGatewayRoute" entry says:
// "Migrate gateway routing to MeshHTTPRoute/MeshTCPRoute, which replace MeshGatewayRoute."
// That is the right target when Kuma keeps doing the routing. This tool emits Gateway API
// instead, which is the right target when the built-in gateway is replaced by a gateway you
// run — the only option left on 3.0, where the built-in gateway is deleted. Both are real
// paths and the manifest does not say which one the operator is taking, so the conversion
// names the alternative rather than guessing.
//
// The TCP half carries an extra caveat: Kuma has never reconciled Gateway API TCPRoute (no
// TCPRouteReconciler exists at v2.14.4 or on master), so a TCPRoute only does something if
// the gateway implementation being adopted reconciles it.
func gatewayRouteSuccessorNote(name string, tcp bool) string {
	if tcp {
		return fmt.Sprintf(
			"MeshGatewayRoute %q: converted to a Gateway API TCPRoute, which suits replacing the "+
				"built-in gateway with one you run. Note Kuma itself never reconciles Gateway API "+
				"TCPRoute — only the gateway implementation you adopt will. If instead you want Kuma "+
				"to keep routing this traffic, upstream's stated replacement is MeshTCPRoute "+
				"(\"MeshHTTPRoute/MeshTCPRoute ... replace MeshGatewayRoute\"), which this tool does "+
				"not generate — write it by hand and drop the TCPRoute.", name)
	}
	return fmt.Sprintf(
		"MeshGatewayRoute %q: converted to a Gateway API HTTPRoute, which suits replacing the "+
			"built-in gateway with one you run (the only option on 3.0, where the built-in gateway "+
			"is deleted). If instead you want Kuma to keep routing this traffic, upstream's stated "+
			"replacement is MeshHTTPRoute (\"MeshHTTPRoute/MeshTCPRoute ... replace "+
			"MeshGatewayRoute\") — note Kuma compiles a Gateway API HTTPRoute into a MeshHTTPRoute "+
			"anyway when its parentRef names a Service or MeshService.", name)
}

// ---- HTTP -------------------------------------------------------------------

func transformGWHTTPRoute(route meshGatewayRoute, gateways *GatewayRefIndex) ([][]byte, []string, error) {
	name := route.Metadata.Name
	namespace := route.Metadata.Namespace
	http := route.Spec.Conf.HTTP
	var warnings []string

	// parentRefs — one per selector entry.
	parentRefs, gatewayNS, w := parentRefsFromSelectors(route.Spec.Selectors, name, namespace, gateways)
	warnings = append(warnings, w...)
	namespace, w = placeRouteWithParentGateway("HTTPRoute", name, namespace, gatewayNS, parentRefs)
	warnings = append(warnings, w...)

	// rules
	var rules []interface{}
	for rIdx, rule := range http.Rules {
		httpRule := map[string]interface{}{}

		// matches
		if len(rule.Matches) > 0 {
			convertedMatches, mw := convertGWHTTPMatches(rule.Matches, name, rIdx)
			warnings = append(warnings, mw...)
			if len(convertedMatches) > 0 {
				httpRule["matches"] = convertedMatches
			}
		}

		// filters
		if len(rule.Filters) > 0 {
			convertedFilters, fw := convertGWFilters(rule.Filters, name, rIdx)
			warnings = append(warnings, fw...)
			if len(convertedFilters) > 0 {
				httpRule["filters"] = convertedFilters
			}
		}

		// backendRefs
		if len(rule.Backends) > 0 {
			backendRefs, bw := convertGWBackends(rule.Backends, name, rIdx)
			warnings = append(warnings, bw...)
			if len(backendRefs) > 0 {
				httpRule["backendRefs"] = backendRefs
			}
		}

		rules = append(rules, httpRule)
	}

	meta := map[string]interface{}{
		"name": name,
	}
	if namespace != "" {
		meta["namespace"] = namespace
	}
	// Carry the mesh forward as a label (see meshLabelFromLabels).
	if meshName := meshNameFromGWRoute(route); meshName != "" {
		meta["labels"] = map[string]interface{}{meshLabel: meshName}
	}

	spec := map[string]interface{}{
		"parentRefs": parentRefs,
	}
	if len(http.Hostnames) > 0 {
		spec["hostnames"] = toStringSlice(http.Hostnames)
	}
	if len(rules) > 0 {
		spec["rules"] = rules
	}

	output := map[string]interface{}{
		"apiVersion": gatewayAPIVersion,
		"kind":       "HTTPRoute",
		"metadata":   meta,
		"spec":       spec,
	}

	b, err := yaml.Marshal(output)
	if err != nil {
		return nil, warnings, fmt.Errorf("marshal HTTPRoute: %w", err)
	}
	grants, gw, err := referenceGrantsForRoute("HTTPRoute", name, namespace, rules)
	warnings = append(warnings, gw...)
	if err != nil {
		return nil, warnings, err
	}
	return append([][]byte{b}, grants...), warnings, nil
}

// ---- TCP --------------------------------------------------------------------

func transformGWTCPRoute(route meshGatewayRoute, gateways *GatewayRefIndex) ([][]byte, []string, error) {
	name := route.Metadata.Name
	namespace := route.Metadata.Namespace
	tcp := route.Spec.Conf.TCP
	var warnings []string

	parentRefs, gatewayNS, w := parentRefsFromSelectors(route.Spec.Selectors, name, namespace, gateways)
	warnings = append(warnings, w...)
	namespace, w = placeRouteWithParentGateway("TCPRoute", name, namespace, gatewayNS, parentRefs)
	warnings = append(warnings, w...)

	var rules []interface{}
	for rIdx, rule := range tcp.Rules {
		backendRefs, bw := convertGWBackends(rule.Backends, name, rIdx)
		warnings = append(warnings, bw...)
		tcpRule := map[string]interface{}{}
		if len(backendRefs) > 0 {
			tcpRule["backendRefs"] = backendRefs
		}
		rules = append(rules, tcpRule)
	}

	meta := map[string]interface{}{
		"name": name,
	}
	if namespace != "" {
		meta["namespace"] = namespace
	}
	if meshName := meshNameFromGWRoute(route); meshName != "" {
		meta["labels"] = map[string]interface{}{meshLabel: meshName}
	}

	spec := map[string]interface{}{
		"parentRefs": parentRefs,
	}
	if len(rules) > 0 {
		spec["rules"] = rules
	}

	output := map[string]interface{}{
		"apiVersion": gatewayAPIVersionAlpha2,
		"kind":       "TCPRoute",
		"metadata":   meta,
		"spec":       spec,
	}

	b, err := yaml.Marshal(output)
	if err != nil {
		return nil, warnings, fmt.Errorf("marshal TCPRoute: %w", err)
	}
	grants, gw, err := referenceGrantsForRoute("TCPRoute", name, namespace, rules)
	warnings = append(warnings, gw...)
	if err != nil {
		return nil, warnings, err
	}
	return append([][]byte{b}, grants...), warnings, nil
}

// ---- ReferenceGrant ---------------------------------------------------------

// referenceGrantAPIVersion is the Gateway API version ReferenceGrant is served
// under on both the standard and experimental channels.
const referenceGrantAPIVersion = "gateway.networking.k8s.io/v1beta1"

// referenceGrantsForRoute builds one ReferenceGrant per backend namespace that
// differs from the route's own namespace, covering every Service the route's
// rules point at there (backendRefs and RequestMirror backendRefs).
//
// Gateway API requires a ReferenceGrant in the target namespace for any
// cross-namespace backendRef, or the route reports ResolvedRefs=False /
// RefNotPermitted and that backend is not programmed. This holds on both targets
// for these routes: their parentRef is a Gateway, which Kuma 2.x's built-in
// gateway reconciled with ReferenceGrant enforcement (kuma#4806, kuma#4944), and
// which on 3.0 only a third-party gateway implementation reconciles — every
// conformant one enforces it. (3.0 additionally extends the check to Kuma's own
// GAMMA translation, kuma#18075.)
//
// When the route has no namespace (MeshGatewayRoute is cluster-scoped, so this
// is the common case) the grant's from-namespace is unknown: the route lands in
// whatever namespace it is applied to. That is reported instead of guessed.
func referenceGrantsForRoute(routeKind, routeName, routeNS string, rules []interface{}) ([][]byte, []string, error) {
	byNS := map[string]map[string]bool{}
	for _, r := range rules {
		rule, _ := r.(map[string]interface{})
		refs, _ := rule["backendRefs"].([]interface{})
		for _, f := range asSlice(rule["filters"]) {
			fm, _ := f.(map[string]interface{})
			if mirror, ok := fm["requestMirror"].(map[string]interface{}); ok {
				if br, ok := mirror["backendRef"].(map[string]interface{}); ok {
					refs = append(refs, br)
				}
			}
		}
		for _, ref := range refs {
			rm, _ := ref.(map[string]interface{})
			ns, _ := rm["namespace"].(string)
			svc, _ := rm["name"].(string)
			if ns == "" || svc == "" || ns == routeNS {
				continue
			}
			if byNS[ns] == nil {
				byNS[ns] = map[string]bool{}
			}
			byNS[ns][svc] = true
		}
	}
	if len(byNS) == 0 {
		return nil, nil, nil
	}
	namespaces := sortedMapKeys(byNS)

	if routeNS == "" {
		return nil, []string{fmt.Sprintf(
			"%s %q has no namespace, but its backendRefs point into namespace(s) %s. Set "+
				"metadata.namespace on the route, then create a ReferenceGrant in each backend namespace "+
				"that differs from it (from: %s in the route's namespace, to: Service). Without the grant "+
				"the backend is not programmed and the route reports RefNotPermitted.",
			routeKind, routeName, strings.Join(namespaces, ", "), routeKind)}, nil
	}

	var docs [][]byte
	var warnings []string
	for _, ns := range namespaces {
		services := sortedMapKeys(byNS[ns])
		to := make([]interface{}, 0, len(services))
		for _, svc := range services {
			to = append(to, map[string]interface{}{"group": "", "kind": "Service", "name": svc})
		}
		grantName := fmt.Sprintf("%s-%s", routeNS, routeName)
		grant := map[string]interface{}{
			"apiVersion": referenceGrantAPIVersion,
			"kind":       "ReferenceGrant",
			"metadata":   map[string]interface{}{"name": grantName, "namespace": ns},
			"spec": map[string]interface{}{
				"from": []interface{}{map[string]interface{}{
					"group":     "gateway.networking.k8s.io",
					"kind":      routeKind,
					"namespace": routeNS,
				}},
				"to": to,
			},
		}
		b, err := yaml.Marshal(grant)
		if err != nil {
			return nil, warnings, fmt.Errorf("marshal ReferenceGrant: %w", err)
		}
		docs = append(docs, b)
		warnings = append(warnings, fmt.Sprintf(
			"%s %q (namespace %s) references Service(s) %s in namespace %s. Generated ReferenceGrant "+
				"%s/%s to allow it — without it the backend is not programmed and the route reports "+
				"RefNotPermitted. Apply it together with the route.",
			routeKind, routeName, routeNS, strings.Join(services, ", "), ns, ns, grantName))
	}
	return docs, warnings, nil
}

func asSlice(v interface{}) []interface{} {
	s, _ := v.([]interface{})
	return s
}

func sortedMapKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// ---- parentRefs -------------------------------------------------------------

// parentRefsFromSelectors converts MeshGatewayRoute selectors into Gateway API parentRefs.
//
// A selector's kuma.io/service tag is the service name of the gateway's pods
// (the MeshGatewayInstance's tag), not the name of the Gateway this tool emits —
// that Gateway is named after the MeshGateway. The tag is resolved through
// GatewayRefIndex to the MeshGateway(s) selecting it, giving the Gateway's name,
// its namespace (the same rule TransformMeshGateway uses) and its listener
// names. The remaining selector tags pick listeners by their tags, the way Kuma
// attached a MeshGatewayRoute to MeshGateway listeners; each matched listener
// becomes one parentRef with sectionName set to that listener's emitted name.
//
// When the tag resolves to no MeshGateway in the input set, the Gateway name is
// derived from the tag itself and flagged for verification.
//
// gatewayNS is the namespace shared by every parent Gateway when all of them
// were resolved through the index, "" otherwise (see placeRouteWithParentGateway).
func parentRefsFromSelectors(selectors []gwSelector, routeName, routeNS string, gateways *GatewayRefIndex) (refs []interface{}, gatewayNS string, warnings []string) {
	allResolved := len(selectors) > 0
	var resolvedNS []string

	for i, sel := range selectors {
		otherTags := map[string]string{}
		for k, v := range sel.Match {
			if k != serviceTagKey {
				otherTags[k] = v
			}
		}

		svcTag := sel.Match[serviceTagKey]
		if svcTag == "" {
			warnings = append(warnings, fmt.Sprintf(
				"MeshGatewayRoute %q selectors[%d]: no kuma.io/service tag — cannot derive Gateway name; set parentRefs[%d].name manually", routeName, i, i))
			ref := newGatewayParentRef("(unknown-gateway)")
			warnings = append(warnings, setHeuristicSectionName(ref, otherTags, routeName, i)...)
			refs = append(refs, ref)
			allResolved = false
			continue
		}

		matched := gateways.gatewaysFor(svcTag)
		if len(matched) == 0 {
			ref, w := heuristicParentRef(svcTag, otherTags, routeName, routeNS, i)
			warnings = append(warnings, w...)
			refs = append(refs, ref)
			allResolved = false
			continue
		}
		if len(matched) > 1 {
			names := make([]string, len(matched))
			for j, g := range matched {
				names[j] = g.name
			}
			warnings = append(warnings, fmt.Sprintf(
				"MeshGatewayRoute %q selectors[%d]: kuma.io/service=%q is selected by more than one MeshGateway (%s) — "+
					"emitted a parentRef for each; remove the ones this route should not attach to",
				routeName, i, svcTag, strings.Join(names, ", ")))
		}

		for _, g := range matched {
			gwNS := ""
			if nss := gateways.gatewayNamespace(g); len(nss) > 0 {
				gwNS = nss[0]
				resolvedNS = appendUniqueSorted(resolvedNS, gwNS)
			} else {
				allResolved = false
				warnings = append(warnings, fmt.Sprintf(
					"MeshGatewayRoute %q selectors[%d]: the namespace of parent Gateway %q is unknown (no "+
						"MeshGatewayInstance in the input set declares kuma.io/service=%q) — parentRefs[].namespace "+
						"omitted, so it defaults to the route's own namespace; set it to the Gateway's namespace",
					routeName, i, g.name, svcTag))
			}

			sections, w := listenerSections(g, otherTags, routeName, i)
			warnings = append(warnings, w...)
			if len(sections) == 0 {
				sections = []string{""}
			}
			for _, section := range sections {
				ref := newGatewayParentRef(g.name)
				if gwNS != "" {
					ref["namespace"] = gwNS
				}
				if section != "" {
					ref["sectionName"] = section
				}
				refs = append(refs, ref)
			}
		}
	}
	if allResolved && len(resolvedNS) == 1 {
		gatewayNS = resolvedNS[0]
	}
	return refs, gatewayNS, warnings
}

func newGatewayParentRef(name string) map[string]interface{} {
	return map[string]interface{}{
		"group": "gateway.networking.k8s.io",
		"kind":  "Gateway",
		"name":  name,
	}
}

// listenerSections returns the emitted names of the listeners of g whose tags
// carry every selector tag besides kuma.io/service. No extra tags means the
// route attaches to the whole Gateway (nil, no sectionName).
func listenerSections(g indexedGateway, otherTags map[string]string, routeName string, i int) ([]string, []string) {
	if len(otherTags) == 0 {
		return nil, nil
	}
	var out []string
	for _, l := range g.listeners {
		ok := true
		for k, v := range otherTags {
			if l.tags[k] != v {
				ok = false
				break
			}
		}
		if ok {
			out = append(out, l.name)
		}
	}
	if len(out) > 0 {
		return out, nil
	}
	return nil, []string{fmt.Sprintf(
		"MeshGatewayRoute %q selectors[%d]: no listener of MeshGateway %q carries tags %v — parentRef attaches to "+
			"every listener of Gateway %q; set parentRefs[%d].sectionName to one of its listener names if that is too broad",
		routeName, i, g.name, otherTags, g.name, i)}
}

// heuristicParentRef derives a parentRef from the kuma.io/service tag alone,
// for a selector whose MeshGateway is not part of the input set.
func heuristicParentRef(svcTag string, otherTags map[string]string, routeName, routeNS string, i int) (map[string]interface{}, []string) {
	var warnings []string
	gwName, gwNS := parseGatewaySvcTag(svcTag)
	ref := newGatewayParentRef(gwName)
	if gwName == "" {
		// Universal-mode: use the raw value as name.
		ref["name"] = svcTag
		warnings = append(warnings, fmt.Sprintf(
			"MeshGatewayRoute %q selectors[%d]: no MeshGateway in the input set selects kuma.io/service=%q, which "+
				"does not follow the K8s _svc_ pattern — used as Gateway name directly; verify this is correct "+
				"(the converted Gateway is named after the MeshGateway, not its service tag)", routeName, i, svcTag))
	} else {
		warnings = append(warnings, fmt.Sprintf(
			"MeshGatewayRoute %q selectors[%d]: no MeshGateway in the input set selects kuma.io/service=%q — "+
				"derived parent Gateway %q from the tag; verify parentRefs[%d] names the converted Gateway, which "+
				"is named after the MeshGateway rather than its service tag", routeName, i, svcTag, gwName, i))
	}
	if gwNS != "" && gwNS != routeNS {
		ref["namespace"] = gwNS
	}
	warnings = append(warnings, setHeuristicSectionName(ref, otherTags, routeName, i)...)
	return ref, warnings
}

// setHeuristicSectionName derives sectionName from listener tags by naming
// convention (a "port: http-8080" tag), used only when the MeshGateway and its
// listener tags are not available.
func setHeuristicSectionName(ref map[string]interface{}, otherTags map[string]string, routeName string, i int) []string {
	if len(otherTags) == 0 {
		return nil
	}
	if sn := sectionNameFromTags(otherTags); sn != "" {
		ref["sectionName"] = sn
		return nil
	}
	return []string{fmt.Sprintf(
		"MeshGatewayRoute %q selectors[%d]: listener tags %v could not be mapped to a sectionName — "+
			"set parentRefs[%d].sectionName to the listener name of the migrated Gateway (e.g. 'http-8080')", routeName, i, otherTags, i)}
}

// placeRouteWithParentGateway picks the route's namespace. MeshGatewayRoute is
// cluster-scoped, so the converted route usually has none — but a Gateway
// listener only accepts routes from its own namespace unless its allowedRoutes
// says otherwise (the converted Gateway sets none). When every parentRef names a
// Gateway resolved to the same namespace (gatewayNS), the route is placed there
// and the then redundant parentRefs[].namespace is dropped. A namespace derived
// only from a service tag's naming pattern is not used: that would be a guess.
func placeRouteWithParentGateway(routeKind, routeName, routeNS, gatewayNS string, parentRefs []interface{}) (string, []string) {
	var warnings []string
	if routeNS == "" {
		if gatewayNS != "" {
			routeNS = gatewayNS
			warnings = append(warnings, fmt.Sprintf(
				"%s %q: MeshGatewayRoute is cluster-scoped; placed the route in namespace %q, the namespace of its "+
					"parent Gateway — a Gateway listener only accepts routes from its own namespace by default "+
					"(allowedRoutes.namespaces.from: Same)", routeKind, routeName, routeNS))
		}
	}
	if routeNS != "" {
		for _, r := range parentRefs {
			ref := r.(map[string]interface{})
			if ref["namespace"] == routeNS {
				delete(ref, "namespace")
			}
		}
	}
	return routeNS, warnings
}

// parseGatewaySvcTag parses a MeshGateway selector service tag.
// Handles "name_ns_svc_port" (standard) and "name_ns_svc" (no port, common for gateways).
// Returns ("", "") for tags that do not follow either K8s pattern (Universal free-form names).
func parseGatewaySvcTag(tag string) (name, namespace string) {
	const svcPortMarker = "_svc_"
	const svcSuffix = "_svc"

	if strings.Contains(tag, svcPortMarker) {
		// Standard K8s format: name_ns_svc_port
		return ParseKumaServiceTag(tag)
	}
	if strings.HasSuffix(tag, svcSuffix) {
		// Gateway K8s format: name_ns_svc (no port)
		nameAndNS := tag[:len(tag)-len(svcSuffix)]
		lastUnderscore := strings.LastIndex(nameAndNS, "_")
		if lastUnderscore != -1 {
			return nameAndNS[:lastUnderscore], nameAndNS[lastUnderscore+1:]
		}
		return nameAndNS, ""
	}
	// Universal free-form name — caller should handle this.
	return "", ""
}

// ---- Match conversions ------------------------------------------------------

func convertGWHTTPMatches(matches []gwHTTPMatch, routeName string, rIdx int) ([]interface{}, []string) {
	var result []interface{}
	var warnings []string

	for _, m := range matches {
		out := map[string]interface{}{}

		if m.Path != nil {
			out["path"] = map[string]interface{}{
				"type":  convertPathMatchType(m.Path.Match),
				"value": m.Path.Value,
			}
		}
		if m.Method != "" {
			out["method"] = m.Method
		}
		if len(m.Headers) > 0 {
			hdrs, hw := convertGWHeaderMatches(m.Headers, routeName, rIdx)
			warnings = append(warnings, hw...)
			if len(hdrs) > 0 {
				out["headers"] = hdrs
			}
		}
		if len(m.QueryParameters) > 0 {
			// field rename: query_parameters → queryParams
			qps := convertGWQueryMatches(m.QueryParameters)
			if len(qps) > 0 {
				out["queryParams"] = qps
			}
		}

		result = append(result, out)
	}
	return result, warnings
}

func convertPathMatchType(t string) string {
	switch strings.ToUpper(t) {
	case "EXACT":
		return "Exact"
	case "PREFIX":
		return "PathPrefix"
	case "REGEX":
		return "RegularExpression"
	default:
		return t
	}
}

func convertGWHeaderMatches(headers []gwHeaderMatch, routeName string, rIdx int) ([]interface{}, []string) {
	var result []interface{}
	var warnings []string
	for _, h := range headers {
		switch strings.ToUpper(h.Match) {
		case "ABSENT", "PRESENT":
			warnings = append(warnings, fmt.Sprintf(
				"HTTPRoute %q rules[%d]: header match type %q for header %q is not supported in Gateway API HTTPRoute — "+
					"this match condition has been dropped; implement it via an ExtensionRef filter or custom policy",
				routeName, rIdx, h.Match, h.Name))
			continue
		}
		out := map[string]interface{}{
			"type": convertHeaderMatchType(h.Match),
			"name": h.Name,
		}
		if h.Value != "" {
			out["value"] = h.Value
		}
		result = append(result, out)
	}
	return result, warnings
}

func convertHeaderMatchType(t string) string {
	switch strings.ToUpper(t) {
	case "EXACT":
		return "Exact"
	case "REGEX":
		return "RegularExpression"
	default:
		return t
	}
}

func convertGWQueryMatches(qps []gwQueryMatch) []interface{} {
	var result []interface{}
	for _, q := range qps {
		result = append(result, map[string]interface{}{
			"type":  convertHeaderMatchType(q.Match), // same enum as headers
			"name":  q.Name,
			"value": q.Value,
		})
	}
	return result
}

// ---- Filter conversions -----------------------------------------------------

func convertGWFilters(filters []gwFilter, routeName string, rIdx int) ([]interface{}, []string) {
	var result []interface{}
	var warnings []string

	for _, f := range filters {
		switch {
		case f.RequestHeader != nil:
			result = append(result, map[string]interface{}{
				"type":                  "RequestHeaderModifier",
				"requestHeaderModifier": convertGWHeaderFilter(f.RequestHeader),
			})

		case f.ResponseHeader != nil:
			result = append(result, map[string]interface{}{
				"type":                   "ResponseHeaderModifier",
				"responseHeaderModifier": convertGWHeaderFilter(f.ResponseHeader),
			})

		case f.Redirect != nil:
			r := f.Redirect
			redirect := map[string]interface{}{}
			if r.Scheme != "" {
				redirect["scheme"] = r.Scheme
			}
			if r.Hostname != "" {
				redirect["hostname"] = r.Hostname
			}
			if r.Port != 0 {
				redirect["port"] = r.Port
			}
			if r.StatusCode != 0 {
				redirect["statusCode"] = r.StatusCode // status_code → statusCode
			}
			if r.Path != nil {
				if pathRewrite := convertGWRewritePath(r.Path); pathRewrite != nil {
					redirect["path"] = pathRewrite
				}
			}
			result = append(result, map[string]interface{}{
				"type":            "RequestRedirect",
				"requestRedirect": redirect,
			})

		case f.Rewrite != nil:
			rw := f.Rewrite
			urlRewrite := map[string]interface{}{}
			if pathRewrite := convertGWRewritePath(rw); pathRewrite != nil {
				urlRewrite["path"] = pathRewrite
			}
			if rw.HostToBackend {
				warnings = append(warnings, fmt.Sprintf(
					"HTTPRoute %q rules[%d]: rewrite.host_to_backend_hostname has no Gateway API equivalent — "+
						"this setting has been dropped; set the host header manually via a RequestHeaderModifier filter if needed",
					routeName, rIdx))
			}
			result = append(result, map[string]interface{}{
				"type":       "URLRewrite",
				"urlRewrite": urlRewrite,
			})

		case f.Mirror != nil:
			m := f.Mirror
			mirror := map[string]interface{}{}
			if m.Percentage != 0 {
				mirror["percent"] = m.Percentage // percentage → percent
			}
			if m.Backend != nil && m.Backend.Destination != nil {
				bref, bw := convertGWSingleBackend(*m.Backend, routeName, rIdx)
				warnings = append(warnings, bw...)
				// Mirror backendRef has no weight.
				delete(bref, "weight")
				mirror["backendRef"] = bref
			}
			result = append(result, map[string]interface{}{
				"type":          "RequestMirror",
				"requestMirror": mirror,
			})
		}
	}
	return result, warnings
}

func convertGWHeaderFilter(f *gwHeaderFilter) map[string]interface{} {
	out := map[string]interface{}{}
	if len(f.Set) > 0 {
		out["set"] = nameValueSlice(f.Set)
	}
	if len(f.Add) > 0 {
		out["add"] = nameValueSlice(f.Add)
	}
	if len(f.Remove) > 0 {
		out["remove"] = f.Remove
	}
	return out
}

func nameValueSlice(nvs []gwNameValue) []interface{} {
	out := make([]interface{}, len(nvs))
	for i, nv := range nvs {
		out[i] = map[string]interface{}{"name": nv.Name, "value": nv.Value}
	}
	return out
}

// convertGWRewritePath converts a gwRewrite into a Gateway API path rewrite spec.
// Returns nil if neither rewrite field is set.
func convertGWRewritePath(rw *gwRewrite) map[string]interface{} {
	if rw.ReplaceFull != "" {
		return map[string]interface{}{
			"type":            "ReplaceFullPath",
			"replaceFullPath": rw.ReplaceFull,
		}
	}
	if rw.ReplacePrefixMatch != "" {
		return map[string]interface{}{
			"type":               "ReplacePrefixMatch",
			"replacePrefixMatch": rw.ReplacePrefixMatch,
		}
	}
	return nil
}

// ---- Backend conversions ----------------------------------------------------

func convertGWBackends(backends []gwBackend, routeName string, rIdx int) ([]interface{}, []string) {
	var result []interface{}
	var warnings []string
	for _, b := range backends {
		ref, bw := convertGWSingleBackend(b, routeName, rIdx)
		warnings = append(warnings, bw...)
		result = append(result, ref)
	}
	return result, warnings
}

func convertGWSingleBackend(b gwBackend, routeName string, rIdx int) (map[string]interface{}, []string) {
	var warnings []string
	ref := map[string]interface{}{
		"kind":  "Service",
		"group": "",
	}

	svcTag := b.Destination["kuma.io/service"]
	if svcTag == "" {
		warnings = append(warnings, fmt.Sprintf(
			"HTTPRoute %q rules[%d]: backend has no kuma.io/service tag — skipped; add backendRefs manually", routeName, rIdx))
		return ref, warnings
	}

	svcName, svcNS := ParseKumaServiceTag(svcTag)
	if svcName == "" {
		// wildcard or unparseable
		warnings = append(warnings, fmt.Sprintf(
			"HTTPRoute %q rules[%d]: backend kuma.io/service=%q could not be parsed — set backendRefs name/namespace manually", routeName, rIdx, svcTag))
		ref["name"] = svcTag
		return ref, warnings
	}

	ref["name"] = svcName
	if svcNS != "" {
		ref["namespace"] = svcNS
	}

	// Extract port from the _svc_PORT segment. Gateway API types backendRefs[].port
	// as int32 (1-65535); a string fails schema validation on every version.
	port := svcPortFromTag(svcTag)
	if port != "" {
		if n, err := strconv.Atoi(port); err == nil && n >= 1 && n <= 65535 {
			ref["port"] = n
		} else {
			warnings = append(warnings, fmt.Sprintf(
				"HTTPRoute %q rules[%d]: backend kuma.io/service=%q ends in %q, which is not a valid port "+
					"number — set backendRefs[].port manually", routeName, rIdx, svcTag, port))
		}
	} else {
		warnings = append(warnings, fmt.Sprintf(
			"HTTPRoute %q rules[%d]: backend kuma.io/service=%q has no port in the svc tag — "+
				"set backendRefs[].port manually", routeName, rIdx, svcTag))
	}

	if b.Weight > 0 {
		ref["weight"] = b.Weight
	}

	return ref, warnings
}

// svcPortFromTag extracts the port string from a K8s-format kuma.io/service tag.
// e.g. "backend_demo_svc_3000" → "3000"; "backend_demo_svc" → "".
func svcPortFromTag(tag string) string {
	const marker = "_svc_"
	idx := strings.LastIndex(tag, marker)
	if idx == -1 {
		return ""
	}
	port := tag[idx+len(marker):]
	if port == "" {
		return ""
	}
	return port
}

// ---- Helpers ----------------------------------------------------------------

// meshNameFromGWRoute extracts the mesh name from a MeshGatewayRoute,
// checking the top-level "mesh" field (Universal) then the kuma.io/mesh label.
func meshNameFromGWRoute(route meshGatewayRoute) string {
	if route.Mesh != "" {
		return route.Mesh
	}
	if v, ok := route.Metadata.Labels["kuma.io/mesh"]; ok {
		return v
	}
	return ""
}

func toStringSlice(ss []string) []interface{} {
	out := make([]interface{}, len(ss))
	for i, s := range ss {
		out[i] = s
	}
	return out
}

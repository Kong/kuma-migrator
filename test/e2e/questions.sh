# Sourced by run.sh (`run.sh questions`): direct admission probes that settle behaviour the
# migrator otherwise infers from source. Writes raw evidence to results/questions-raw.md;
# results/questions.md is the hand-written summary of it.
# shellcheck shell=bash

q_k8s() { # target file → one line
  local ctx; ctx=$(kctx "$( [[ $1 == v2 ]] && echo $CLUSTER_V2 || echo $CLUSTER_V3)")
  kubectl --context "$ctx" apply --dry-run=server -f "$2" 2>&1 | tr '\n' ' ' | sed "s|$E2E_WORK|\$E2E_WORK|g"
}
q_uni() { # target file → one line (real apply, deleted afterwards by the CP reset)
  local cp ver; if [[ $1 == v2 ]]; then cp=$UCP_V2 ver=$KM_V2; else cp=$UCP_V3 ver=$KM_V3; fi
  "$(kumactl_bin "$ver")" --config-file "$(kumactl_cfg "$cp")" "${@:3}" apply -f "$2" 2>&1 | tr '\n' ' '
}
q_kumactl() { # target args...
  local cp ver; if [[ $1 == v2 ]]; then cp=$UCP_V2 ver=$KM_V2; else cp=$UCP_V3 ver=$KM_V3; fi
  "$(kumactl_bin "$ver")" --config-file "$(kumactl_cfg "$cp")" "${@:2}" 2>&1 | head -2 | tr '\n' ' ' | cut -c1-160
}
q_json() { # target args... → raw stdout
  local cp ver; if [[ $1 == v2 ]]; then cp=$UCP_V2 ver=$KM_V2; else cp=$UCP_V3 ver=$KM_V3; fi
  "$(kumactl_bin "$ver")" --config-file "$(kumactl_cfg "$cp")" "${@:2}" 2>&1
}
row() { printf '| %s | %s |\n' "$1" "$(echo "$2" | sed 's/|/\\|/g' | cut -c1-400)"; }

k8s_policy() { # kind ns targetRef-yaml body-yaml
  printf 'apiVersion: kuma.io/v1alpha1\nkind: %s\nmetadata: {name: probe, namespace: %s, labels: {kuma.io/mesh: default}}\nspec:\n  targetRef: %s\n%s\n' "$@"
}
uni_policy() { # kind targetRef-yaml body-yaml
  printf 'type: %s\nname: probe\nmesh: default\nspec:\n  targetRef: %s\n%s\n' "$@"
}

cmd_questions() {
  local d=$E2E_WORK/q out=$RESULTS/questions-raw.md f
  mkdir -p "$d"
  {
    echo "# Raw evidence for questions.md"
    echo
    echo "Generated by \`run.sh questions\` against Kong Mesh $KM_V2 / $KM_V3 ($E2E_PLATFORM)."
    echo "Kubernetes: \`kubectl apply --dry-run=server\`. Universal: real \`kumactl apply\`."

    echo; echo "## MeshCircuitBreaker with only healthyPanicThreshold"; echo
    echo "| Probe | Result |"; echo "|---|---|"
    local od
    for od in "healthyPanicThreshold: 50" "{healthyPanicThreshold: 50, detectors: {}}" "{healthyPanicThreshold: 50, disabled: true}"; do
      [[ $od == healthy* ]] && od="{$od}"
      k8s_policy MeshCircuitBreaker kong-mesh-system "{kind: Mesh}" "  to:
  - targetRef: {kind: Mesh}
    default: {outlierDetection: $od}" >"$d/mcb.yaml"
      uni_policy MeshCircuitBreaker "{kind: Mesh}" "  to:
  - targetRef: {kind: Mesh}
    default: {outlierDetection: $od}" >"$d/mcb-u.yaml"
      row "3.0 k8s \`$od\`" "$(q_k8s v3 "$d/mcb.yaml")"
      row "3.0 uni \`$od\`" "$(q_uni v3 "$d/mcb-u.yaml")"
      row "2.14 k8s \`$od\`" "$(q_k8s v2 "$d/mcb.yaml")"
    done

    echo; echo "## Top-level targetRef.kind: MeshGateway on 2.14"; echo
    echo "| Probe | Result |"; echo "|---|---|"
    local kind ns body
    for kind in MeshTimeout MeshTrafficPermission MeshAccessLog; do
      case $kind in
        MeshTimeout) body='  to:
  - targetRef: {kind: Mesh}
    default: {idleTimeout: 10s}' ;;
        MeshTrafficPermission) body='  from:
  - targetRef: {kind: Mesh}
    default: {action: Allow}' ;;
        MeshAccessLog) body='  from:
  - targetRef: {kind: Mesh}
    default: {backends: [{type: File, file: {path: /dev/stdout}}]}' ;;
      esac
      for ns in kong-mesh-system kuma-demo; do
        k8s_policy "$kind" "$ns" "{kind: MeshGateway, name: edge-gateway}" "$body" >"$d/gw.yaml"
        row "2.14 k8s $kind in $ns" "$(q_k8s v2 "$d/gw.yaml")"
      done
      uni_policy "$kind" "{kind: MeshGateway, name: edge-gateway}" "$body" >"$d/gw-u.yaml"
      row "2.14 uni $kind" "$(q_uni v2 "$d/gw-u.yaml")"
    done

    echo; echo "## Mesh fields on 3.0"; echo
    echo "| Probe | Result |"; echo "|---|---|"
    local i=0 spec
    for spec in "constraints: {dataplaneProxy: {requirements: [{tags: {kuma.io/zone: '*'}}]}}" \
      "mtls: {enabledBackend: ca-1, backends: [{name: ca-1, type: builtin}]}" \
      "meshServices: {mode: Everywhere}" "meshServices: {mode: ReachableBackends}" "meshServices: {mode: Disabled}" \
      "meshServices: {mode: Exclusive}" "metrics: {enabledBackend: prom, backends: [{name: prom, type: prometheus}]}" \
      "routing: {defaultForbidMeshExternalServiceAccess: true}"; do
      i=$((i + 1))
      printf 'apiVersion: kuma.io/v1alpha1\nkind: Mesh\nmetadata: {name: probe-%s}\nspec:\n  %s\n' $i "$spec" >"$d/mesh.yaml"
      printf 'type: Mesh\nname: probe-%s\n%s\n' $i "$spec" >"$d/mesh-u.yaml"
      row "3.0 k8s \`$spec\`" "$(q_k8s v3 "$d/mesh.yaml")"
      row "3.0 uni \`$spec\`" "$(q_uni v3 "$d/mesh-u.yaml")"
      row "3.0 uni stored spec of probe-$i" "$(q_json v3 get mesh probe-$i -o json | jq -c 'del(.creationTime,.modificationTime,.kri,.labels,.name,.type)' 2>/dev/null)"
    done

    echo; echo "## MeshIdentity Extension providers (site/content/topics/external-pki.md)"; echo
    echo "| Probe | Result |"; echo "|---|---|"
    awk -v d="$d" '/^```yaml/{f=1; n++; next} /^```/{f=0} f && n<=3 {print > (d "/mi-" n ".yaml")}' "$ROOT/site/content/topics/external-pki.md"
    local n name
    for n in 1 2 3; do
      name=$(awk '/name: (vault|acmpca|certmanager)$/{print $2; exit}' "$d/mi-$n.yaml")
      sed 's/kuma.io\/mesh: payments/kuma.io\/mesh: default/' "$d/mi-$n.yaml" >"$d/mi-$n-k.yaml"
      { echo "type: MeshIdentity"; echo "name: probe-$name"; echo "mesh: default"; sed -n '/^spec:/,$p' "$d/mi-$n.yaml"; } >"$d/mi-$n-u.yaml"
      row "2.14 k8s $name" "$(q_k8s v2 "$d/mi-$n-k.yaml")"
      row "3.0 k8s $name" "$(q_k8s v3 "$d/mi-$n-k.yaml")"
      row "2.14 uni $name" "$(q_uni v2 "$d/mi-$n-u.yaml")"
      row "3.0 uni $name" "$(q_uni v3 "$d/mi-$n-u.yaml")"
    done
    sleep 10
    for n in vault acmpca certmanager; do
      row "2.14 uni probe-$n status" "$(q_json v2 get meshidentity probe-$n --mesh default -o json | jq -c '[.status.conditions[]? | {type, reason, message}]' 2>/dev/null)"
    done

    echo; echo "## 2.14: MeshIdentity on a mesh without meshServices.mode: Exclusive"; echo
    echo "| Probe | Result |"; echo "|---|---|"
    printf 'type: Mesh\nname: probe-mi\n' >"$d/mi-mesh.yaml"
    printf 'type: MeshIdentity\nname: probe-bundled\nmesh: probe-mi\nspec:\n  selector: {dataplane: {matchLabels: {}}}\n  provider: {type: Bundled, bundled: {meshTrustCreation: Enabled, insecureAllowSelfSigned: true, autogenerate: {enabled: true}}}\n' >"$d/mi-bundled.yaml"
    row "2.14 uni Mesh probe-mi (no meshServices)" "$(q_uni v2 "$d/mi-mesh.yaml")"
    row "2.14 uni Bundled MeshIdentity in probe-mi" "$(q_uni v2 "$d/mi-bundled.yaml")"
    sleep 25
    row "status, meshServices unset" "$(q_json v2 get meshidentity probe-bundled --mesh probe-mi -o json | jq -c '[.status.conditions[]? | {type, reason, message}]' 2>/dev/null)"
    printf 'type: Mesh\nname: probe-mi\nmeshServices: {mode: Exclusive}\n' >"$d/mi-mesh.yaml"
    q_uni v2 "$d/mi-mesh.yaml" >/dev/null; sleep 10
    row "status, meshServices.mode: Exclusive" "$(q_json v2 get meshidentity probe-bundled --mesh probe-mi -o json | jq -c '[.status.conditions[]? | {type, reason, message}]' 2>/dev/null)"

    echo; echo "## kumactl types used by v3DeleteCommand (2.14 Universal)"; echo
    echo "| Kind | \`kumactl delete <type> does-not-exist\` |"; echo "|---|---|"
    local typ m
    while read -r kind typ m; do
      local margs=(); [[ -n $m ]] && margs=(--mesh "$m")
      row "$kind \`$typ\`" "$(q_kumactl v2 delete "$typ" does-not-exist "${margs[@]}")"
    done <<'EOT'
TrafficPermission traffic-permission default
TrafficRoute traffic-route default
TrafficLog traffic-log default
TrafficTrace traffic-trace default
HealthCheck health-check default
CircuitBreaker circuit-breaker default
Retry retry default
Timeout timeout default
RateLimit rate-limit default
FaultInjection fault-injection default
VirtualOutbound virtual-outbound default
ProxyTemplate proxytemplate default
ExternalService external-service default
ZoneIngress zone-ingress
ZoneEgress zone-egress
OPAPolicy opa-policy default
MeshGateway meshgateway default
MeshGatewayRoute meshgatewayroute default
MeshGlobalRateLimit meshglobalratelimit default
EOT
    row "\`kumactl config use-context\` ($KM_V2)" "$(q_kumactl v2 config use-context x)"

    echo; echo "## 3.0: removed kinds and dangling backendRef"; echo
    echo "| Probe | Result |"; echo "|---|---|"
    printf 'apiVersion: kuma.io/v1alpha1\nkind: TrafficPermission\nmesh: default\nmetadata: {name: probe}\nspec:\n  sources: [{match: {kuma.io/service: "*"}}]\n  destinations: [{match: {kuma.io/service: "*"}}]\n' >"$d/tp.yaml"
    row "3.0 k8s TrafficPermission" "$(q_k8s v3 "$d/tp.yaml")"
    k8s_policy MeshAccessLog kong-mesh-system "{kind: Mesh}" "  rules:
  - default: {backends: [{type: OpenTelemetry, openTelemetry: {backendRef: {kind: MeshOpenTelemetryBackend, labels: {kuma.io/display-name: no-such-backend}}}}]}" >"$d/mal.yaml"
    k8s_policy MeshTrace kong-mesh-system "{kind: Mesh}" "  default: {backends: [{type: OpenTelemetry, openTelemetry: {backendRef: {kind: MeshOpenTelemetryBackend, labels: {kuma.io/display-name: no-such-backend}}}}]}" >"$d/mt.yaml"
    row "3.0 k8s MeshAccessLog, backendRef to no MOTB" "$(q_k8s v3 "$d/mal.yaml")"
    row "3.0 k8s MeshTrace, backendRef to no MOTB" "$(q_k8s v3 "$d/mt.yaml")"
    for f in mal mt; do
      { echo "type: $(awk '/^kind:/{print $2}' "$d/$f.yaml")"; echo "name: probe"; echo "mesh: default"; sed -n '/^spec:/,$p' "$d/$f.yaml"; } >"$d/$f-u.yaml"
      row "3.0 uni $f, backendRef to no MOTB" "$(q_uni v3 "$d/$f-u.yaml")"
    done
    k8s_policy MeshTimeout kong-mesh-system "{kind: Mesh}" "  to:
  - targetRef: {kind: Mesh}
    default: {idleTimeout: 10s}" | sed 's/labels: {kuma.io\/mesh: default}/labels: {kuma.io\/mesh: default, kuma.io\/origin: global}/' >"$d/origin.yaml"
    row "3.0 k8s policy with kuma.io/origin: global on a zone" "$(q_k8s v3 "$d/origin.yaml")"
    row "2.14 k8s policy with kuma.io/origin: global on a zone" "$(q_k8s v2 "$d/origin.yaml")"
  } >"$out"
  log "wrote $out"
}
